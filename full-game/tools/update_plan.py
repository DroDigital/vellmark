#!/usr/bin/env python3
"""Generate docs/PLAN.md from the brief, phase files, and docs/STATE.md.

Usage:
  python3 tools/update_plan.py          rewrite docs/PLAN.md
  python3 tools/update_plan.py --check  exit 1 if docs/PLAN.md is out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLAN = ROOT / "docs" / "PLAN.md"
BRIEF = ROOT / "docs" / "brief"


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def fail(message):
    sys.exit("update_plan: " + message)


def state_field(text, name):
    match = re.search(r"\*\*" + re.escape(name) + r":\*\*\s*(.+)", text)
    return match[1].strip() if match else "Unknown"


def state_section(text, heading):
    match = re.search(r"^## " + re.escape(heading) + r"\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return match[1].strip() if match else "Unknown"


def block(filename, start, end=None):
    """Return the text from the line starting with `start` up to `end`."""
    text = read(BRIEF / filename)
    begin = text.find(start)
    if begin < 0:
        fail(f"cannot find '{start}' in {filename}; update the markers in this script")
    stop = len(text)
    if end is not None:
        stop = text.find(end, begin + len(start))
        if stop < 0:
            fail(f"cannot find '{end}' in {filename}; update the markers in this script")
    return text[begin:stop].strip()


def first_table(text):
    rows = [line for line in text.split("\n") if line.startswith("|")]
    if not rows:
        fail("expected a table in the brief")
    return "\n".join(rows)


def parse_phases():
    phases = []
    for path in sorted((ROOT / "phases").glob("P[0-9][0-9]-*.md")):
        text = read(path)
        title = re.search(r"^# (.+)$", text, re.M)
        goal = re.search(r"^\*\*Goal:\*\* (.+)$", text, re.M)
        gate = re.search(r"^## Owner gate: (.+)$", text, re.M)
        tasks = re.findall(r"^- \[( |x|X)\] \*\*(P\d\d-T\d\d[a-z]?)\*\* (.+)$", text, re.M)
        if not (title and goal and tasks):
            fail(f"could not parse {path.name}")
        phases.append({
            "file": path.name,
            "title": title[1],
            "goal": goal[1],
            "gate": gate[1] if gate else "",
            "tasks": [(mark != " ", task_id, name) for mark, task_id, name in tasks],
        })
    if not phases:
        fail("no phase files found")
    return phases


def bar(done, total, width=20):
    filled = round(width * done / total) if total else 0
    return "#" * filled + "-" * (width - filled)


def build():
    state = read(ROOT / "docs" / "STATE.md")
    phases = parse_phases()
    current_file = state_field(state, "Phase file").strip("`").split("/")[-1]
    status = state_field(state, "Status")
    done = sum(sum(1 for t in p["tasks"] if t[0]) for p in phases)
    total = sum(len(p["tasks"]) for p in phases)

    out = [
        "# Vellmark: the living plan",
        "",
        "> Generated by `tools/update_plan.py` from `docs/brief/`, `phases/`, and `docs/STATE.md`. "
        "Do not edit this file by hand. To change the plan, edit those sources and record the change in "
        "[`PLAN_CHANGES.md`](PLAN_CHANGES.md).",
        "",
        "## Where things stand",
        "",
        f"**Overall:** `{bar(done, total)}` {done} of {total} tasks ({round(100 * done / total)}%)",
        "",
        "| | |",
        "|---|---|",
        f"| **Current phase** | [{current_file}](../phases/{current_file}) |",
        f"| **Status** | {status} |",
        f"| **Current task** | {state_field(state, 'Current task')} |",
        "",
    ]
    for heading in ["Exact next step", "Waiting on the owner", "Blockers", "Known issues"]:
        out += [f"**{heading}:** {state_section(state, heading)}", ""]

    out += ["## Phases", "", "| Phase | Progress | Tasks | Status | Owner gate |", "|---|---|---|---|---|"]
    for phase in phases:
        d = sum(1 for t in phase["tasks"] if t[0])
        n = len(phase["tasks"])
        if phase["file"] == current_file:
            label = status
        elif d == n:
            label = "Done"
        elif d:
            label = "Partly done"
        else:
            label = "Not started"
        out.append(
            f"| [{phase['title']}](../phases/{phase['file']}) | `{bar(d, n, 10)}` | {d}/{n} | {label} | {phase['gate'] or '-'} |"
        )

    out += [
        "",
        "## What we are building",
        "",
        block("0-overview.md", "You are building **VELLMARK**", "The game takes structural").replace(
            "You are building **VELLMARK**, a", "**Vellmark** is a", 1
        ),
        "",
        "### The three pillars",
        "",
        first_table(block("0a-pillars-and-releases.md", "## The three pillars", "## The pillar test")),
        "",
        "### Releases",
        "",
        first_table(block("0a-pillars-and-releases.md", "## Releases", "**Release rules.**")),
        "",
        "### Technology",
        "",
        first_table(block("1a-core-constraints.md", "**The stack.**", "SDL3 is a platform layer")),
        "",
        "### The world",
        "",
        block("4a-world.md", "**Premise.**", "**Scale.**"),
        "",
        block("4a-world.md", "**Geography.**", "**Generation.**"),
        "",
        "### Content targets",
        "",
        first_table(block("4b-content-and-story.md", "**Content target", "Enemy, boss, and loot targets")),
        "",
        block("4b-content-and-story.md", "**Major questlines:**", "**Endings.**"),
        "",
        "### Endings",
        "",
        block("4b-content-and-story.md", "1. **The Restoration:**", "All routes share one final dungeon"),
        "",
        "### Enemies and bosses",
        "",
        first_table(block("5c-enemies-and-bosses.md", "### Enemies", "**Families:**")),
        "",
        first_table(block("5c-enemies-and-bosses.md", "### Bosses", "Every boss has")),
        "",
        "### Loot",
        "",
        first_table(block("5d-loot.md", "**Item tiers,**", "**Content targets:**")),
        "",
        first_table(block("5d-loot.md", "**Content targets:**", "- A deterministic")),
        "",
        "## Task checklist",
        "",
    ]
    for phase in phases:
        d = sum(1 for t in phase["tasks"] if t[0])
        out += [f"<details><summary><b>{phase['title']}</b> ({d}/{len(phase['tasks'])})</summary>", "", phase["goal"], ""]
        for is_done, task_id, name in phase["tasks"]:
            out.append(f"- [{'x' if is_done else ' '}] **{task_id}** {name}")
        out += ["", "</details>", ""]

    out += [
        "## Plan changes",
        "",
        read(ROOT / "docs" / "PLAN_CHANGES.md").split("\n", 1)[1].strip(),
        "",
        "## Where the details live",
        "",
        "- Full design: [`docs/brief/`](brief/)",
        "- What is built in which release: [`docs/SCOPE.md`](SCOPE.md)",
        "- World bible: [`docs/WORLD_BIBLE.md`](WORLD_BIBLE.md)",
        "- Story and quests: [`docs/script/`](script/)",
        "- Voice cast and budget: [`docs/voice/cast-and-budget.md`](voice/cast-and-budget.md)",
        "- Build order: [`phases/README.md`](../phases/README.md)",
        "- Technical decisions: [`docs/DECISIONS.md`](DECISIONS.md)",
        "- Human test steps: [`docs/PLAYTEST_CHECKLIST.md`](PLAYTEST_CHECKLIST.md)",
        "",
    ]
    return "\n".join(out)


def main():
    content = build()
    if "--check" in sys.argv:
        if not PLAN.exists() or read(PLAN) != content:
            sys.exit("docs/PLAN.md is out of date. Run: python3 tools/update_plan.py")
        print("docs/PLAN.md is up to date")
        return
    PLAN.write_text(content, encoding="utf-8", newline="\n")
    print("Updated docs/PLAN.md")


if __name__ == "__main__":
    main()
